"""Reviewed adversarial *fixture*: probe denied operations inside one Docker CI guest.

This fixture is deliberately fixed in the repository, not generated by an LLM
or accepted from an issue/comment. It never attempts to contact external hosts
and never reads/prints secret VALUES. Tests permissions only on disposable guest
paths and safely cleans up if any forbidden write unexpectedly succeeds.
A passing report is an OBSERVATION, not general hostile-code certification.
"""
import json
import os
from pathlib import Path
import runpy
import socket
import sys

_PROBE = Path(__file__).with_name("sandbox_runtime_probe.py")
_baseline = runpy.run_path(str(_PROBE))["inspect"]()

def _write_forbidden(path):
    try:
        with open(path, "xb") as target:
            target.write(b"opdb-isolation-negative-control")
    except OSError:
        return True
    else:
        try:
            Path(path).unlink()
        except OSError:
            pass
        return False

def _docker_socket_absent():
    # Do NOT connect to a Docker daemon even if misconfigured: detecting the
    # socket itself means the isolation test failed.
    return all(
        not Path(name).exists()
        for name in ("/var/run/docker.sock", "/run/docker.sock")
    )

def _secret_names_absent():
    # Check presence only; do not log sensitive environment variable values.
    exact = {"GITHUB_TOKEN", "GH_TOKEN", "OPENAI_API_KEY",
             "YANDEX_API_KEY", "AWS_SECRET_ACCESS_KEY",
             "GOOGLE_APPLICATION_CREDENTIALS", "DOCKER_HOST"}
    return not any(key in os.environ for key in exact)

def _seccomp_filter_active():
    try:
        lines = Path("/proc/self/status").read_text(encoding="ascii").splitlines()
    except OSError:
        return False
    for line in lines:
        if line.startswith("Seccomp:"):
            return line.partition(":")[2].strip() == "2"
    return False

def inspect():
    checks = {
        "root_write_denied": _write_forbidden("/etc/__opdb_disposable_probe"),
        "source_write_denied": _write_forbidden("/work/__opdb_disposable_probe"),
        "docker_socket_absent": _docker_socket_absent(),
        "secret_names_absent": _secret_names_absent(),
        "seccomp_filter_active": _seccomp_filter_active(),
        "baseline_confinement_pass": (
            set(_baseline) == {
                "non_root_uid", "root_filesystem_read_only",
                "work_mount_read_only", "tmpfs_noexec",
                "network_only_loopback", "outbound_tcp_denied",
                "cgroup_memory_128m", "cgroup_pids_32",
                "cgroup_cpu_half", "no_new_privileges", "no_effective_caps"
            } and all(value is True for value in _baseline.values())
        ),
        "no_host_network_interface": set(
            name for _, name in socket.if_nameindex()
        ) == {"lo"},
    }
    return checks

if __name__ == "__main__":
    results = inspect()
    passed = bool(results) and all(value is True for value in results.values())
    print(json.dumps({
        "probe": "fixed-reviewed-denied-operations",
        "checked": results,
        "passed": passed,
        "untrusted_model_code_executed": False,
        "hostile_code_sandbox_attested": False,
    }, sort_keys=True))
    sys.exit(0 if passed else 1)
